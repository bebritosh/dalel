"""Build the static exports used by the backend-free demo (npm run build:mock).

Runs the real pipeline on the synthetic demo case (eval/cases/demo-001, fixture
mode, temp DB, no network), confirms every extracted field and writes:

    frontend/public/mock/pretenziya_demo.docx   real DOCX from the backend
    frontend/public/mock/pretenziya_demo.pdf    real PDF (only if LibreOffice found)
    frontend/src/mock/claimText.ts              the same claim text for the UI

Re-run after changing the claim text, template or rules/legal_refs.json:
    .venv/bin/python scripts/make_mock_exports.py
tests/test_mock_exports.py fails if the committed claim text drifts.
"""

from __future__ import annotations

import json
import sys
import tempfile
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

DEMO = ROOT / "eval/cases/demo-001"
PUBLIC = ROOT / "frontend/public/mock"
CLAIM_TS = ROOT / "frontend/src/mock/claimText.ts"


def demo_exports() -> dict[str, bytes | str | None]:
    """Run the demo case end to end; return claim text, DOCX and PDF bytes."""
    from fastapi.testclient import TestClient
    from sqlmodel import Session, SQLModel, create_engine

    import app.models  # noqa: F401  (register tables)
    from app.core import config
    from app.core.db import get_session
    from app.main import app

    tmp = Path(tempfile.mkdtemp(prefix="dalel-mock-"))
    saved = (config.settings.data_dir, config.settings.llm_mode, config.settings.openai_api_key)
    config.settings.data_dir = str(tmp / "data")
    config.settings.llm_mode = "fixture"
    config.settings.openai_api_key = ""
    engine = create_engine(f"sqlite:///{tmp}/mock.db", connect_args={"check_same_thread": False})
    SQLModel.metadata.create_all(engine)

    def session_override() -> Iterator[Session]:
        with Session(engine) as s:
            yield s

    app.dependency_overrides[get_session] = session_override
    try:
        client = TestClient(app)
        body = client.post("/cases").json()
        cid, h = body["id"], {"X-Case-Token": body["access_token"]}
        for name, kind, mime in (
            ("receipt.png", "receipt", "image/png"),
            ("chat.txt", "chat", "text/plain"),
        ):
            r = client.post(
                f"/cases/{cid}/documents", headers=h, data={"kind": kind},
                files={"file": (name, (DEMO / name).read_bytes(), mime)},
            )
            r.raise_for_status()
        for fact in client.post(f"/cases/{cid}/extract", headers=h).json():
            client.patch(
                f"/facts/{fact['id']}", headers=h, json={"confirmed_by_user": True}
            ).raise_for_status()
        claim = client.post(f"/cases/{cid}/claim", headers=h)
        claim.raise_for_status()
        docx = client.get(f"/cases/{cid}/export?format=docx", headers=h)
        docx.raise_for_status()
        pdf = client.get(f"/cases/{cid}/export?format=pdf", headers=h)
        return {
            "text": claim.json()["text"],
            "docx": docx.content,
            "pdf": pdf.content if pdf.status_code == 200 else None,
        }
    finally:
        app.dependency_overrides.clear()
        engine.dispose()
        config.settings.data_dir, config.settings.llm_mode, config.settings.openai_api_key = saved


def claim_ts(text: str) -> str:
    lines = ",\n".join(f"  {json.dumps(line, ensure_ascii=False)}" for line in text.split("\n"))
    return (
        "// Generated by scripts/make_mock_exports.py from the real backend on the\n"
        "// synthetic demo case. Do not edit by hand: re-run the script.\n"
        f"export const mockClaimText = [\n{lines},\n].join(\"\\n\");\n"
    )


def main() -> None:
    out = demo_exports()
    PUBLIC.mkdir(parents=True, exist_ok=True)
    (PUBLIC / "pretenziya_demo.docx").write_bytes(out["docx"])
    print("wrote", (PUBLIC / "pretenziya_demo.docx").relative_to(ROOT))
    if out["pdf"]:
        (PUBLIC / "pretenziya_demo.pdf").write_bytes(out["pdf"])
        print("wrote", (PUBLIC / "pretenziya_demo.pdf").relative_to(ROOT))
    else:
        print("LibreOffice not found: PDF skipped (mock PDF button will show 503 text)")
    CLAIM_TS.write_text(claim_ts(out["text"]), encoding="utf-8")
    print("wrote", CLAIM_TS.relative_to(ROOT))


if __name__ == "__main__":
    main()
